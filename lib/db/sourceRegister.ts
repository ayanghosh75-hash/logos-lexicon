// Legacy compatibility helper for existing entry citations
export const SOURCE_REGISTER: Record<string, SourceCitation> = Object.fromEntries(
  Object.entries(SOURCE_REGISTRY).map(([id, s]) => [
    id,
    {
      sourceId: s.sourceId,
      shortTitle: s.shortTitle,
      fullCitation: s.attributionFormat,
      classification:
        s.copyrightStatus === 'Public domain'
          ? 'Public domain'
          : s.copyrightStatus === 'Original commissioned'
          ? 'Original commissioned material'
          : 'Citation-only source',
      licenseDetails: s.licenceName,
    },
  ])
);

export function getSourceById(sourceId: string): SourceRegistryEntry | undefined {
  return SOURCE_REGISTRY[sourceId];
}

export function getAllSources(): SourceRegistryEntry[] {
  return Object.values(SOURCE_REGISTRY);
}

export function getApprovedSources(): SourceRegistryEntry[] {
  return Object.values(SOURCE_REGISTRY).filter(
    (s) =>
      s.importStatus === 'Approved for reuse' ||
      s.importStatus === 'Approved with attribution' ||
      s.importStatus === 'Approved with share-alike conditions'
  );
}
